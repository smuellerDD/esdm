/* Instantiate, reseed, generate twice - the sweep of the record above */
static int esdm_hash_drbg_kat(struct esdm_drbg_state *drbg,
			      const uint8_t *ent_nonce, size_t ent_noncelen,
			      uint8_t *act, size_t actlen)
{
	if (esdm_drbg_seed(drbg, ent_nonce, ent_noncelen, kat_pers,
			   sizeof(kat_pers)))
		return -EFAULT;

	if (esdm_drbg_seed(drbg, kat_ent_reseed, sizeof(kat_ent_reseed),
			   kat_addtl_reseed, sizeof(kat_addtl_reseed)))
		return -EFAULT;

	if (esdm_drbg_generate(drbg, act, actlen, kat_addtl1,
			       sizeof(kat_addtl1)) < 0)
		return -EFAULT;

	if (esdm_drbg_generate(drbg, act, actlen, kat_addtl2,
			       sizeof(kat_addtl2)) < 0)
		return -EFAULT;

	return 0;
}

static int esdm_hash_drbg_selftest(void)
{
	uint8_t act[sizeof(kat_exp)];
	uint8_t mod[sizeof(kat_ent_nonce)];
	ESDM_DRBG_HASH_CTX_ON_STACK(drbg_stack);
	int ret;

	CKINT(esdm_drbg_healthcheck_sanity(drbg_stack));

	CKINT(esdm_hash_drbg_kat(drbg_stack, kat_ent_nonce,
				 sizeof(kat_ent_nonce), act, sizeof(act)));
	CKINT(esdm_kat_check(act, kat_exp, sizeof(kat_exp)));

	/*
	 * Seed material off by its first byte must not produce that output -
	 * the DRBG is instantiated afresh for it, as the state it is in after
	 * the sweep above is not the one the known answer belongs to.
	 */
	esdm_drbg_zero(drbg_stack);
	CKINT(esdm_kat_modify(mod, kat_ent_nonce, sizeof(mod)));
	CKINT(esdm_hash_drbg_kat(drbg_stack, mod, sizeof(mod), act,
				 sizeof(act)));
	CKINT(esdm_kat_check_differs(act, kat_exp, sizeof(kat_exp)));

out:
	esdm_drbg_zero(drbg_stack);
	return ret;
}

